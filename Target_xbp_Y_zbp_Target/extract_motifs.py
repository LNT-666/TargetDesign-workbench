def reverse_complement(seq):
    return str(Seq(seq).reverse_complement())

def find_all_y(genome, y):
    y_plus = y.upper()
    y_minus = reverse_complement(y_plus)
    occurrences = []
    for chrom in genome.keys():
        seq = str(genome[chrom][:]).upper()
        for strand, motif in (("+", y_plus), ("-", y_minus)):
            pos = seq.find(motif)
            while pos != -1:
                occurrences.append((chrom, pos, pos + len(motif), strand))
                pos = seq.find(motif, pos + 1)

    # 回文 Y 序列在同一位置不应重复计数，优先保留正链。
    seen = set()
    unique_occurrences = []
    for occurrence in occurrences:
        key = occurrence[:3]
        if key in seen:
            continue
        seen.add(key)
        unique_occurrences.append(occurrence)
    return unique_occurrences

def process_region(chrom_seq, search_start, search_end, chrom, motif, flank_len, side):
    """
    ????????????????????????????????????????motif??????????????????????[search_start, search_end) ??????????????????????
    ????????? {full_seq: [(chrom, strand, full_start, full_end, motif_start, motif_end)]}
    ??????????????????????????? full_seq ???????????????????????????????'????'?????????strand ?????????????????????????????????????????????????
    ??????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????side ?????????????
    """
    motif_plus = motif.upper()
    motif_minus = reverse_complement(motif_plus)

    print(f"  motif (+) regex: {iupac_to_regex(motif_plus)}")
    print(f"  motif (-) regex: {iupac_to_regex(motif_minus)}")

    candidates = defaultdict(list)
    seq_len = len(chrom_seq)

    # ?????????????????????????????????????????????????????? side ?????????
    for pos, motif_var in find_all_iupac_matches(chrom_seq, motif_plus):
        motif_len = len(motif_var)
        if not (search_start <= pos < search_end):
            continue
        motif_start = pos
        motif_end = pos + motif_len
        if side == "upstream":
            full_start = max(0, motif_start - flank_len)
            full_end = motif_end
            up = chrom_seq[full_start:motif_start]
            full = up + motif_var
        else:  # downstream
            full_start = motif_start
            full_end = min(seq_len, motif_end + flank_len)
            down = chrom_seq[motif_end:full_end]
            full = motif_var + down
        candidates[full].append((chrom, 'plus', full_start, full_end, motif_start, motif_end))

    # ???????????????????????????????side ??????????????????????????????????????????????????????
    # ??????????????????????????????????????????????????????????????????????????????????????????????
    effective_side = "downstream" if side == "upstream" else "upstream"

    for pos, motif_var in find_all_iupac_matches(chrom_seq, motif_minus):
        motif_len = len(motif_var)
        if not (search_start <= pos < search_end):
            continue
        motif_start = pos
        motif_end = pos + motif_len
        if effective_side == "upstream":
            full_start = max(0, motif_start - flank_len)
            full_end = motif_end
            up = chrom_seq[full_start:motif_start]
            full = up + motif_var
        else:  # downstream
            full_start = motif_start
            full_end = min(seq_len, motif_end + flank_len)
            down = chrom_seq[motif_end:full_end]
            full = motif_var + down
        candidates[full].append((chrom, 'minus', full_start, full_end, motif_start, motif_end))

    return candidates

def generate_tsv_lines(candidates, motif, flank_len, side, min_dist):
    """生成去重后的查询 TSV，供 Off-target search 使用；positions 记录 motif 匹配位置信息"""
    unique_seqs = list(candidates.keys())
    tsv_lines = []
    tsv_lines.append(f"# motif={motif} flank_len={flank_len} side={side} min_dist={min_dist}\n")
    tsv_lines.append("qid\tsequence\tpositions\n")
    for idx, seq in enumerate(unique_seqs):
        qid = f"uniq_{idx}"
        pos_list = candidates[seq]
        pos_json = json.dumps(pos_list)
        tsv_lines.append(f"{qid}\t{seq}\t{pos_json}\n")
    return tsv_lines

